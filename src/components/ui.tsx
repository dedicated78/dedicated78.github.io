export function PlatformBadge({ platform, compact }: { platform: Platform | 'all'; compact?: boolean }) {
  if (platform === 'all') return <span className="badge badge-all">All channels</span>;
  const m = PLATFORM_META[platform];
  return (
    <span className={cx('badge', `badge-${platform}`)} title={m.label}>
      <span className="badge-dot" aria-hidden="true" />
      {compact ? m.short : m.label}
    </span>
  );
}

export function StatusPill({ status }: { status: ItemStatus }) {
  return (
    <span className={cx('status', `status-${status}`)} title={STATUS_META[status].hint}>
      {STATUS_META[status].label}
    </span>
  );
}

export function AiLabel({ provenance }: { provenance: Provenance | null | undefined }) {
  if (!provenance) return null;
  const title = `Generated by ${provenance.generated_by}${provenance.agents.length ? ` with ${provenance.agents.join(', ')}` : ''} · ${provenance.model} · ${fmtDateTime(provenance.generated_at)}`;
  return (
    <span className="ai-label" title={title}>
      <IconSpark width={14} height={14} />
      {provenance.mode === 'demo' ? 'AI draft (demo template)' : 'AI-generated'}
      {provenance.edited_by_user ? ' · edited' : ''}
    </span>
  );
}

