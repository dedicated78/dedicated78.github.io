import { launch, newPage, login, shot, check, summary, BASE } from '../lib.mjs';
const b = await launch();

console.log('\nMOSTAFA: deal workflow');
const m = await newPage(b);
await login(m, 'mostafa@demo.test');
await m.waitForSelector('text=New from outreach');
await shot(m, '10-bd-dashboard');
const nav = await m.locator('nav[aria-label=Main]').first().innerText();
check(/Deals/.test(nav) && /Clients/.test(nav) && !/Settings/.test(nav), 'BD nav: Deals + Clients, no Settings');
check(await m.getByText('Owner is interested in Maps visibility').first().isVisible(), 'handoff note shown prominently on dashboard');
check((await m.getByText('New qualified leads').locator('xpath=following-sibling::p').first().innerText()) === '1', 'New qualified leads = 1');
await m.getByRole('link', { name: 'Open deal' }).first().click();
await m.waitForURL(/#\/deals\/[0-9a-f-]{36}$/);
await m.waitForSelector('text=Business development');
await shot(m, '11-deal-detail');
check(await m.getByText('Handoff note').first().isVisible(), 'deal shows handoff note');
check(await m.getByText('Spoke with Jane').first().isVisible(), 'deal shows outreach history');
await m.getByLabel('Discovery notes').fill('Wants more calls from Maps. Budget ~1.5k/mo.');
await m.getByLabel('Estimated value').fill('1500');
await m.getByLabel('Billing').selectOption('Monthly');
await m.getByLabel('Services discussed').fill('Local SEO, GBP optimisation');
await m.getByLabel('Decision maker').fill('Jane Example');
check(await m.getByText('You have unsaved changes').isVisible(), 'dirty indicator shows');
await m.getByRole('button', { name: 'Save changes' }).click();
await m.waitForSelector('text=Deal saved');
check(await m.getByText('All changes saved').isVisible(), 'clean indicator after save');
await m.reload();
await m.waitForSelector('text=Business development');
check((await m.getByLabel('Estimated value').inputValue()) === '1500', 'values persisted after reload');
// stage control
await m.getByRole('button', { name: 'Discovery' }).click();
await m.waitForSelector('text=Stage: Discovery');
await m.getByRole('button', { name: 'Proposal Sent' }).click();
await m.waitForSelector('text=Stage: Proposal Sent');
check((await m.locator('[aria-current=step]').innerText()).includes('Proposal Sent'), 'stage progress reflects current stage');
// deal-mode activity
await m.getByRole('button', { name: 'Log activity' }).click();
await m.getByRole('radio', { name: 'Meeting' }).check({ force: true });
check((await m.getByRole('dialog').getByLabel('Lead status').count()) === 0, 'deal-mode activity has no lead-status field');
const dlg = m.getByRole('dialog');
await dlg.getByLabel('Outcome').selectOption('Meeting Held');
await dlg.getByLabel('Short notes').fill('Kickoff call went well, sending proposal.');
await dlg.getByLabel('Next action').fill('Send proposal');
await dlg.getByRole('button', { name: 'Save activity' }).click();
await m.waitForSelector('text=Activity logged');
check((await m.getByLabel('Next action').first().inputValue()) === 'Send proposal', 'deal next action updated by activity');
// mark won -> convert
await m.getByRole('button', { name: 'Mark won' }).click();
await m.getByRole('button', { name: 'Mark as won' }).click();
await m.getByRole('heading', { name: 'Convert to client' }).waitFor();
const cv = m.getByRole('dialog');
await shot(m, '12-convert');
check((await cv.getByLabel('Agreed price').inputValue()) === '1500', 'convert prefilled with deal value');
check((await cv.getByLabel('Business name').inputValue()) === 'Demo Roofing Co (Sample)', 'convert prefilled with business');
check((await cv.getByLabel('Service', { exact: true }).inputValue()).includes('Local SEO'), 'convert prefilled with services');
await cv.getByLabel('Start date').fill('2026-10-15');
await cv.getByRole('button', { name: 'Create client' }).click();
await m.waitForURL(/#\/clients\/[0-9a-f-]{36}$/);
await m.waitForSelector('text=Access checklist');
await shot(m, '13-client-bd');
check((await m.getByLabel('Notes').isDisabled()), 'BD sees client read-only');
check((await m.locator('li:has-text("Google Business Profile")').count()) === 1, 'default access checklist created');
await m.goto(`${BASE}/deals?view=won`);
await m.waitForSelector('text=Demo Roofing Co (Sample)');
check(true, 'won deal listed under Won');
await m.goto(`${BASE}/settings`);
await m.waitForURL(/#\/dashboard/);
check(true, 'BD redirected away from Settings');

console.log('\nADMIN: onboarding');
const a = await newPage(b);
await login(a, 'mehedi@demo.test');
await a.waitForSelector('text=Needs attention');
await shot(a, '14-admin-dashboard');
check(await a.getByText('Waiting on access · Demo Roofing Co (Sample)').isVisible(), 'attention: client waiting for access');
check((await a.getByText('Clients onboarding').locator('xpath=following-sibling::p').first().innerText()) === '1', 'clients onboarding = 1');
check(await a.getByText('Recent activity').isVisible() && (await a.locator('text=Kickoff call went well').count()) >= 0, 'recent activity renders');
await a.getByRole('link', { name: 'Clients' }).first().click();
await a.waitForSelector('text=Demo Roofing Co (Sample)');
await shot(a, '15-clients');
await a.getByRole('link', { name: 'Demo Roofing Co (Sample)' }).first().click();
await a.waitForSelector('text=Access checklist');
await a.getByRole('button', { name: 'Payment Pending' }).click();
await a.waitForSelector('text=Onboarding: Payment Pending');
await a.getByLabel('Google Business Profile status').selectOption('Received');
await a.waitForTimeout(600);
await a.getByLabel('Website / CMS status').selectOption('Requested');
await a.getByLabel('Website / CMS note').fill('WP login invite sent');
await a.getByLabel('Website / CMS note').blur();
await a.waitForTimeout(800);
await a.reload();
await a.waitForSelector('text=Access checklist');
check((await a.getByLabel('Google Business Profile status').inputValue()) === 'Received', 'access item persisted');
check((await a.getByLabel('Website / CMS note').inputValue()) === 'WP login invite sent', 'access note persisted');
check(await a.locator('header, section').filter({ hasText: 'Partial' }).first().isVisible(), 'access status derived as Partial');
await a.getByLabel('Payment status').selectOption('Paid');
await a.getByLabel('Notes').fill('Kickoff booked for Oct 15.');
await a.getByRole('button', { name: 'Save changes' }).click();
await a.waitForSelector('text=Client saved');
await shot(a, '16-client-admin');
// global search
await a.getByLabel('Search leads and clients').fill('demo roof');
await a.waitForSelector('[role=listbox] >> text=Clients');
check((await a.locator('[role=option]').count()) === 2, 'global search returns the lead and the client');
await a.keyboard.press('Escape');
// archive
await a.goto(`${BASE}/leads`);
await a.waitForSelector('text=Demo Roofing Co (Sample)');
await a.getByRole('button', { name: 'Archive Demo Roofing Co (Sample)' }).click();
await a.getByRole('button', { name: 'Archive', exact: true }).click();
await a.waitForSelector('text=Lead archived');
check((await a.getByText('Demo Roofing Co (Sample)').count()) === 0, 'archived lead hidden from default list');
await a.getByLabel('Archived').check();
await a.waitForSelector('text=Demo Roofing Co (Sample)');
check(true, 'archived lead visible under Archived filter');

// client delete (admin) - the only DELETE the browser can issue
await a.goto(`${BASE}/clients`);
await a.getByRole('link', { name: 'Demo Roofing Co (Sample)' }).first().click();
await a.waitForSelector('text=Access checklist');
await a.getByRole('button', { name: 'Delete' }).click();
await a.getByRole('button', { name: 'Delete client' }).click();
await a.waitForSelector('text=Client deleted');
await a.waitForSelector('text=No clients yet.');
check(true, 'admin deletes the (mistaken) client after confirmation; lead and deal are kept');

console.log('\nMAJEDA after archive');
const mj = await newPage(b);
await login(mj, 'majeda@demo.test');
await mj.waitForSelector('text=Today’s queue');
check((await mj.getByText('Demo Roofing Co (Sample)').count()) === 0, 'archived lead gone from Majeda');

await b.close();
process.exit(summary([['mostafa', m], ['admin', a], ['majeda', mj]]));
